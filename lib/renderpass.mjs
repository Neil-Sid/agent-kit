// kit render: tries the runtime render pass in lib/render.js on your scenarios. Static transforms stop being
// recomputed, and static meshes that share a material draw as one BatchedMesh. Each scenario runs without and with
// the pass (same frames, same seed): behavior and screenshots are compared and both sides are timed (see verify.mjs).
// --apply installs it, only if every scenario kept the same behavior and at least one got faster (or with --force):
// kit-render.js is written to the project and loaded from index.html, right after the import map.
//
//   kit render <scenario...> [--runs 3] [--settle 90] [--batch [--min-batch 8]] [--apply [--force]]
//   kit render --revert
import fs from 'node:fs'
import path from 'node:path'
import { installRender } from './render.js'
import { compare } from './verify.mjs'

const BEGIN = '<!-- kit:render -->', END = '<!-- /kit:render -->'
const FILE = 'kit-render.js'
export const injectFor = f => `(async () => { const THREE = await import('three'); (${installRender})(THREE, ${JSON.stringify(optsOf(f))}) })()`
const optsOf = f => ({ settle: +(f.settle || 90), minBatch: +(f['min-batch'] || 8), batch: !!f.batch })

function revert(dir) {
  const html = path.join(dir, 'index.html')
  const text = fs.readFileSync(html, 'utf8')
  const out = text.replace(new RegExp(`${BEGIN}[\\s\\S]*?${END}\\r?\\n?`), '')
  if (out !== text) fs.writeFileSync(html, out)
  fs.rmSync(path.join(dir, FILE), { force: true })
  return out !== text
}

function apply(dir, opts) {
  const html = path.join(dir, 'index.html')
  const text = fs.readFileSync(html, 'utf8')
  const map = text.match(/<script type="importmap">[\s\S]*?<\/script>/)
  if (!map || !/"three"\s*:/.test(map[0])) throw new Error('index.html has no import map for "three"; import kit-render.js from your entry module instead')
  revert(dir)
  fs.writeFileSync(path.join(dir, FILE), [
    '// Generated by agent-kit (kit render --apply); remove with kit render --revert. Add ?norender to the URL to compare.',
    "import * as THREE from 'three'",
    `const installRender = ${installRender}`,
    `if (!new URLSearchParams(location.search).has('norender')) installRender(THREE, ${JSON.stringify(opts)})`, ''].join('\n'))
  const fresh = fs.readFileSync(html, 'utf8'), at = fresh.indexOf(map[0]) + map[0].length
  fs.writeFileSync(html, `${fresh.slice(0, at)}\n  ${BEGIN}<script type="module" src="./${FILE}"></script>${END}${fresh.slice(at)}`)
}

const summary = s => !s ? 'the pass did not start (no scene rendered through THREE.Scene?)' :
  `${s.frozen} static objects (${s.skipped} in skipped subtrees), ${s.batches} batches holding ${s.batched} meshes, ` +
  `+${s.extraMB.toFixed(1)} MB geometry; ${s.woken} woke up and ${s.dropped} left a batch during the run`

export async function render(dir, config, names, flags) {
  if (flags.revert) { console.log(revert(dir) ? `kit render: removed ${FILE} and its script tag` : 'kit render: nothing to remove'); return {} }
  if (!names.length) throw new Error(`name scenarios to try (have: ${Object.keys(config.scenarios || {}).join(', ')})`)
  const opts = optsOf(flags)
  const inject = injectFor(flags)
  const sides = [{ label: 'off', dir }, { label: 'pass', dir, inject, collect: 'JSON.stringify(globalThis.__kitRender?.stats ?? null)' }]
  console.log(`kit render: without vs with the render pass (settle ${opts.settle} renders, ${opts.batch ? `batching groups of ${opts.minBatch}+` : 'batching off'})`)
  let same = true, faster = false
  for (const name of names) {
    const r = await compare(config, name, sides, flags, path.join(dir, '.kit', 'render'))
    r.lines.splice(1, 0, `  pass        ${summary(r.extra)}`)
    console.log(['', ...r.lines].join('\n'))
    same &&= r.same && !r.unjudged      // installing needs every frame checked
    faster ||= r.faster
  }
  if (flags.apply) {
    if ((same && faster) || flags.force) { apply(dir, opts); console.log(`\napplied: ${FILE} written and loaded from index.html (kit render --revert removes it)`) }
    else console.log(`\nnot applied: ${!same ? 'the game looked or behaved differently, or a frame was too noisy to check' :'no scenario got measurably faster'} (--force applies anyway)`)
  }
  return { failed: !same }
}
